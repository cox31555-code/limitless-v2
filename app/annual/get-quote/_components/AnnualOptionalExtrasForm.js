const AnnualOptionalExtrasForm = ({ form }) => {
  const vehicleReg = form.watch("vehicleDetails.registrationNumber") || "your vehicle";

  const handleSelection = (extraId, value) => {
    form.setValue(`optionalExtras.${extraId}`, value, { shouldValidate: false });
  };

  return (
    <ComponentWrapper title="Optional Extras">
      <div className={styles.extrasContent}>
        <div className={styles.extrasIntro}>
          <h2 className={styles.introTitle}>Enhance your cover</h2>
          <p className={styles.introSubtitle}>
            Add extra protection to your policy. All of these are optional.
          </p>
        </div>

        <div className={styles.extrasGrid}>
          {OPTIONAL_EXTRAS.map((extra) => (
            <div key={extra.id} className={styles.extraOption}>
              <div className={styles.extraCard}>
                <div className={styles.iconSection}>
                  <div className={styles.icon}>{extra.icon}</div>
                </div>

                <div className={styles.contentSection}>
                  <h3 className={styles.extraName}>{extra.title}</h3>
                  <p className={styles.extraPrice}>{extra.price}</p>
                  <p className={styles.extraDescription}>{extra.description}</p>
                </div>
              </div>

              <div className={styles.selectionWrapper}>
                <p className={styles.selectionQuestion}>
                  Add to <strong>{vehicleReg}</strong>?
                </p>
                <div className={styles.buttonGroup}>
                  <button
                    type="button"
                    className={`${styles.optionBtn} ${
                      form.watch(`optionalExtras.${extra.id}`) === true ? styles.optionBtnYes : ""
                    }`}
                    onClick={() => handleSelection(extra.id, true)}
                  >
                    Yes
                  </button>
                  <button
                    type="button"
                    className={`${styles.optionBtn} ${
                      form.watch(`optionalExtras.${extra.id}`) === false ? styles.optionBtnNo : ""
                    }`}
                    onClick={() => handleSelection(extra.id, false)}
                  >
                    No
                  </button>
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>
    </ComponentWrapper>
  );
};

export default AnnualOptionalExtrasForm;
